import { chromium } from '@playwright/test';
import { strict as assert } from 'node:assert';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading', { name: '我的曲库', exact: true }).waitFor();
await page.getByRole('button', { name: '外观预设' }).click();
await page.getByRole('button', { name: /浅色唱片室/ }).click();
assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
await page.keyboard.press('Escape');
await page.locator('input[type=file]').first().setInputFiles(['tests/fixtures/微风.lrc', 'tests/fixtures/微风.mp3', 'tests/fixtures/夜航.mp3']);
await page.getByRole('heading', { name: '微风', exact: true }).waitFor();
await page.getByRole('button', { name: '播放', exact: true }).click();
await page.waitForFunction(() => document.querySelector('audio')?.currentTime > 0.4);
const start = await page.locator('audio').evaluate(a => a.currentTime);
await page.getByRole('button', { name: '外观预设' }).click();
await page.getByRole('button', { name: /极简舞台/ }).click();
await page.keyboard.press('Escape');
assert.equal(await page.locator('audio').evaluate(a => a.paused), false);
assert.ok(await page.locator('audio').evaluate(a => a.currentTime) >= start);
await page.getByRole('button', { name: '收藏当前歌曲' }).click();
await page.getByRole('button', { name: /我的喜欢/ }).click();
assert.equal(await page.locator('.track-row').count(), 1);
await page.getByRole('button', { name: /本地音乐/ }).click();
await page.getByPlaceholder('搜索音乐、歌手').fill('不存在');
assert.equal(await page.locator('.track-row').count(), 0);
await page.getByPlaceholder('搜索音乐、歌手').fill('');
await page.getByRole('button', { name: '下一首' }).click();
await page.getByRole('heading', { name: '夜航', exact: true }).waitFor();
await page.getByRole('button', { name: '上一首' }).click();
await page.getByRole('heading', { name: '微风', exact: true }).waitFor();
await page.getByRole('button', { name: '打开播放界面', exact: true }).click();
await page.getByRole('button', { name: '风吹过安静的海' }).click();
assert.ok(await page.locator('audio').evaluate(a => a.currentTime) >= 5);
await page.getByRole('button', { name: '返回曲库' }).click();
await page.reload();
await page.waitForFunction(() => document.querySelectorAll('.track-row').length === 2);
assert.equal(await page.locator('html').getAttribute('data-theme'), 'stage');
assert.equal(await page.locator('audio').evaluate(a => a.paused), true);
await mkdir('screenshots', { recursive: true });
for (const [name, label] of [['glass','雾蓝玻璃'], ['light','浅色唱片室'], ['stage','极简舞台']]) {
  await page.getByRole('button', { name: '外观预设' }).click();
  await page.getByRole('button', { name: new RegExp(label) }).click();
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `screenshots/${name}.png`, fullPage: true });
}
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(350);
assert.ok(await page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right <= 1));
await page.screenshot({ path: 'screenshots/mobile.png', fullPage: true });
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
await page.getByRole('button', { name: '外观预设' }).click();
await page.getByRole('button', { name: /雾蓝玻璃/ }).click();
await page.keyboard.press('Escape');
await page.setViewportSize({ width: 1440, height: 1000 });
await page.waitForTimeout(350);
await page.getByRole('button', { name: '移除 夜航' }).click();
await page.getByRole('button', { name: '移除 微风' }).click();
assert.equal(await page.locator('.track-row').count(), 0);
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'screenshots/empty.png', fullPage: true });
assert.deepEqual(errors, []);
console.log('PASS: 导入、真实播放、歌词定位、主题不中断、收藏搜索、切歌、刷新恢复、移除、手机宽度与浏览器错误检查');
await browser.close();
