import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true,channel:'msedge'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://127.0.0.1:5173');
await page.locator('input[type=file]').first().waitFor({state:'attached'});
await page.waitForFunction(() => !document.querySelector('input[type=file]').disabled);
await page.locator('input[type=file]').first().setInputFiles(['tests/fixtures/微风.mp3','tests/fixtures/夜航.mp3']);
await page.getByRole('heading',{name:'微风',exact:true}).waitFor();
await page.getByRole('button',{name:'播放',exact:true}).click();
await page.waitForFunction(() => document.querySelector('audio').currentTime > .3);
await page.getByRole('slider',{name:'音量',exact:true}).fill('0.32');
assert.equal(await page.locator('audio').evaluate(a => a.volume), .32);
await page.getByRole('button',{name:'静音',exact:true}).click();
assert.equal(await page.locator('audio').evaluate(a => a.muted), true);
await page.getByRole('button',{name:'取消静音',exact:true}).click();
await page.getByRole('slider',{name:'播放进度',exact:true}).fill('8');
assert.ok(await page.locator('audio').evaluate(a => a.currentTime) >= 8);
await page.locator('input[type=file]').nth(1).setInputFiles({name:'任意名字.txt',mimeType:'text/plain',buffer:Buffer.from('第一行纯文本\n第二行纯文本')});
await page.getByRole('button',{name:'打开播放界面',exact:true}).click();
await page.getByRole('button',{name:'第一行纯文本'}).waitFor();
assert.equal(await page.getByRole('button',{name:'第一行纯文本'}).isDisabled(),true);
await page.getByRole('button',{name:'顺序播放',exact:true}).click();
await page.getByRole('button',{name:'随机播放',exact:true}).click();
await page.locator('audio').evaluate(a => {a.currentTime = a.duration - .1;});
await page.waitForFunction(() => document.querySelector('audio').currentTime < 3 && !document.querySelector('audio').paused);
assert.equal(await page.getByRole('heading',{name:'微风',exact:true}).count(),1);
await page.getByRole('button',{name:'单曲循环',exact:true}).click();
await page.getByRole('button',{name:'下一首'}).click();
await page.getByRole('heading',{name:'夜航',exact:true}).waitFor();
await page.locator('audio').evaluate(a => {a.currentTime = a.duration - .1;});
await page.waitForFunction(() => document.querySelector('audio').ended);
assert.equal(await page.getByRole('button',{name:'播放',exact:true}).count(),1);
await page.getByRole('button',{name:'播放队列'}).click();
assert.equal(await page.locator('.queue-list>button').count(),2);
await page.getByRole('button',{name:'关闭播放队列'}).click();
await page.getByRole('button',{name:'返回曲库'}).click();
await page.getByRole('button',{name:'移除 夜航'}).click();
await page.getByRole('heading',{name:'微风',exact:true}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(350);
await page.getByRole('button',{name:'打开播放界面',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'第一行纯文本'}).isVisible(),true);
await page.getByRole('button',{name:'返回曲库'}).click();
await page.getByRole('button',{name:'打开导航'}).click();
await page.waitForTimeout(350);
assert.ok(await page.getByRole('button',{name:/我的喜欢/}).isVisible());
await page.getByRole('button',{name:/我的喜欢/}).click();
await page.waitForTimeout(350);
assert.ok(await page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right <= 1));
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.cover-frame').evaluate(el => getComputedStyle(el).transitionDuration),'0s');
const unavailable = await browser.newPage();
await unavailable.addInitScript(() => {indexedDB.open = () => {throw new Error('storage unavailable');};});
await unavailable.goto('http://127.0.0.1:5173');
await unavailable.waitForFunction(() => !document.querySelector('input[type=file]').disabled);
await unavailable.locator('input[type=file]').first().setInputFiles('tests/fixtures/微风.mp3');
await unavailable.getByRole('heading',{name:'微风',exact:true}).waitFor();
await unavailable.getByRole('button',{name:'播放',exact:true}).click();
await unavailable.waitForFunction(() => document.querySelector('audio').currentTime > .2);
console.log('PASS: 音量、静音、定位、TXT、单曲循环、顺序结束、队列、移除当前歌、手机歌词导航、减少动态效果、存储失败时继续播放');
await browser.close();
